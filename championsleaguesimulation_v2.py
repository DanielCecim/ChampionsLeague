class Player(threading.Thread):
    def __init__(self, team, name, role, team_arrival_barrier, field_barrier):
        super().__init__(daemon=True)
        self.team = team
        self.pname = name
        self.role = role
        self.team_arrival_barrier = team_arrival_barrier
        self.field_barrier = field_barrier

    def __str__(self):
        return f"{self.team.name}-{self.pname}({role_str(self.role)})"

    # --- Ball actions ---

    def pass_ball(self):
        roles = allowed_pass_targets(self)
        candidates = [p for p in self.team.players if p is not self and p.role in roles]
        if not candidates:
            return None
        target = random.choice(candidates)
        ball.set_owner(target)
        log(f"➡️  {self} passes to {target}.")
        return target

    def consider_shot(self):
        if self.role != Role.FWD:
            return False
        if random.random() < PROB_SHOT_FWD:
            # Shot decision
            on_target = random.random() < PROB_SHOT_ON_TARGET
            other_team = teamA if self.team.name == "B" else teamB
            gk = [p for p in other_team.players if p.role == Role.GK][0]
            if on_target:
                if random.random() < PROB_SAVE_BY_GK:
                    log(f"🧤 Shot by {self} ON TARGET! Saved by {gk}!")
                    ball.set_owner(gk)
                else:
                    with score_lock:
                        scoreboard[self.team.name] += 1
                    log(f"🥅 GOAL! {self} scores!  Score: {scoreboard['A']} - {scoreboard['B']}")
                    restart_after_goal(self.team)
            else:
                log(f"🎯 Shot by {self} is OFF target. Goal kick to {gk}.")
                ball.set_owner(gk)
            return True
        return False

    # --- Fouls only against FWD owner ---

    def attempt_foul_on_forward_owner(self):
        """
        If the current owner is a Forward, allow at most one opposing DEF/MID to foul.
        This triggers a penalty and pauses play.
        """
        # Only eligible roles can foul
        if self.role not in (Role.DEF, Role.MID):
            return
        owner = ball.get_owner()
        if (owner is None or owner.team.name == self.team.name or owner.role != Role.FWD):
            return

        # Try to become the single fouler for this incident
        if not foul_lock.acquire(blocking=False):
            return

        committed = False
        try:
            # Re-check consistency just before committing
            owner_now = ball.get_owner()
            if owner_now is not owner or not pause_event.is_set():
                return
            # Role-based foul probability
            p = PROB_FOUL_DEF if self.role == Role.DEF else PROB_FOUL_MID
            if random.random() < p:
                committed = True
                log(f"🟨 {self} fouls {owner}! PENALTY to Team {owner.team.name}!")
                self.handle_penalty(fouled_forward=owner)
        finally:
            # Hold the lock through the penalty; otherwise release immediately
            if not committed:
                foul_lock.release()

    def handle_penalty(self, fouled_forward):
        """Pause everyone, take the penalty, assign post-outcome possession, resume."""
        # Serialise with other stoppages
        stoppage_lock.acquire()
        try:
            # Pause the world
            pause_event.clear()
            log("⏸️  Play paused for penalty setup.")
            time.sleep(0.8)  # setup time

            # Penalty taker = fouled forward's team (could be the same forward)
            shooting_team = fouled_forward.team
            other_team = teamA if shooting_team.name == "B" else teamB
            gk = [p for p in other_team.players if p.role == Role.GK][0]

            # Penalty shot (use same on-target/save params)
            on_target = random.random() < PROB_SHOT_ON_TARGET
            if on_target and random.random() >= PROB_SAVE_BY_GK:
                with score_lock:
                    scoreboard[shooting_team.name] += 1
                log(f"🥅 PENALTY GOAL by {fouled_forward}! Score: {scoreboard['A']} - {scoreboard['B']}")
                restart_after_goal(shooting_team)
            else:
                # saved or off target -> GK possession
                if on_target:
                    log(f"🧤 Penalty by {fouled_forward} SAVED by {gk}!")
                else:
                    log(f"🎯 Penalty by {fouled_forward} OFF target. {gk} restarts.")
                ball.set_owner(gk)

            time.sleep(0.4)
            log("▶️  Play resumes after penalty.")
            pause_event.set()
        finally:
            stoppage_lock.release()
            foul_lock.release()

    # --- Steals ---

    def attempt_steal_window(self):
        owner = ball.get_owner()
        allowed, p = can_steal(self, owner)
        if not allowed or not pause_event.is_set():
            return
        if random.random() < p:
            got = ball.mutex.acquire(timeout=0.01)
            if got:
                try:
                    if ball.get_owner() is owner and pause_event.is_set():
                        ball.set_owner(self)
                        log(f"🧨 STEAL! {self} dispossesses {owner}.")
                finally:
                    ball.mutex.release()

    def ball_handler_tick(self):
        if not pause_event.is_set():
            return
        got = ball.mutex.acquire(timeout=0.05)
        if not got:
            return
        try:
            if ball.get_owner() is not self or not pause_event.is_set():
                return
            # Shot (FWD only) else pass
            if not self.consider_shot():
                self.pass_ball()
        finally:
            ball.mutex.release()

    # --- Lifecycle ---

    def run(self):
        log(f"🚌 {self} arriving at stadium.")
        self.team_arrival_barrier.wait()
        log(f"🧳 {self} heads to locker room.")
        time.sleep(random.uniform(0.1, 0.4))

        log(f"🚶 {self} walking to tunnel.")
        self.field_barrier.wait()

        stadium.anthem_start.wait()
        for line in ANTHEM_LINES:
            log(f"🎶 {self} sings: {line}")
            time.sleep(0.03)

        stadium.match_start.wait()

        while not end_event.is_set():
            # Wait for next match tick, respecting pauses
            pause_event.wait()
            tick_event.wait(timeout=0.2)
            if end_event.is_set():
                break
            # If I own the ball, act; otherwise try foul/steal appropriately
            if ball.get_owner() is self:
                self.ball_handler_tick()
            else:
                # First: a single opposing DEF/MID may foul a FWD owner
                self.attempt_foul_on_forward_owner()
                # If no foul happened (or I'm not eligible), maybe steal
                self.attempt_steal_window()

        log(f"🏁 {self} done.")

