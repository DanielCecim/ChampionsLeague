def build_team(name):
    team = Team(name)
    # 1 GK, 4 DEF, 4 MID, 2 FWD
    roles = [Role.GK] + [Role.DEF]*4 + [Role.MID]*4 + [Role.FWD]*2
    random.shuffle(roles)
    for i in range(1, TEAM_SIZE + 1):
        p = Player(team, f"P{i:02d}", roles[i-1], team.arrival_barrier, team.field_barrier)
        team.players.append(p)
    # Ensure exactly one GK
    gks = [p for p in team.players if p.role == Role.GK]
    if len(gks) == 0:
        team.players[0].role = Role.GK
    elif len(gks) > 1:
        for p in gks[1:]:
            p.role = Role.DEF
    return team

teamA = build_team("A")
teamB = build_team("B")

# ---------------------------
# Orchestration
# ---------------------------

class MatchOrchestrator:
    def __init__(self):
        self.clock = MatchClock(tick_event, end_event)

    def start(self):
        log("🚨 Simulation boot.")

        # Start fans
        fans = [Fan(i+1) for i in range(NUM_FANS)]
        for f in fans: f.start()

        time.sleep(0.4)
        log("🔓 Stadium gates OPEN.")
        stadium.gates_open.set()

        # Start players
        for p in teamA.players + teamB.players:
            p.start()

        # Anthem
        time.sleep(1.0)
        log("🎤 Anthem starts.")
        stadium.anthem_start.set()

        time.sleep(0.8)
        # Kickoff: random owner
        kickoff_owner = random.choice(teamA.players + teamB.players)
        ball.set_owner(kickoff_owner)
        log("🏟️ Match starts!")
        stadium.match_start.set()

        # Start clock
        self.clock.start()

        # Wait end
        end_event.wait()
        time.sleep(0.3)
        log(f"🔚 Final score: A {scoreboard['A']} - {scoreboard['B']} B")

def main():
    MatchOrchestrator().start()

if __name__ == "__main__":
    main()